CREATE TABLE hubs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(20) NOT NULL,
  name VARCHAR(100) NOT NULL,
  city VARCHAR(60) NOT NULL,
  service_radius_m INT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_hubs_code UNIQUE (code)
);

CREATE TABLE products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR(40) NOT NULL,
  name VARCHAR(120) NOT NULL,
  category VARCHAR(50) NOT NULL,
  unit_label VARCHAR(30) NOT NULL,
  diet VARCHAR(10) NOT NULL,
  storage_zone VARCHAR(10) NOT NULL,
  shelf_life_days INT,
  private_label BOOLEAN NOT NULL DEFAULT FALSE,
  description VARCHAR(500),
  CONSTRAINT uq_products_sku UNIQUE (sku)
);

-- Each hub has its own range and price.
CREATE TABLE hub_products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hub_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  price_paise INT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_hub_products UNIQUE (hub_id, product_id),
  CONSTRAINT fk_hub_products_hub FOREIGN KEY (hub_id) REFERENCES hubs (id),
  CONSTRAINT fk_hub_products_product FOREIGN KEY (product_id) REFERENCES products (id)
);

-- Stock is held per hub, per batch, with a use-by date for perishables.
CREATE TABLE stock_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hub_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  batch_code VARCHAR(40) NOT NULL,
  received_at TIMESTAMP NOT NULL,
  use_by DATE,
  quantity INT NOT NULL,
  bin VARCHAR(20),
  CONSTRAINT fk_stock_batches_hub FOREIGN KEY (hub_id) REFERENCES hubs (id),
  CONSTRAINT fk_stock_batches_product FOREIGN KEY (product_id) REFERENCES products (id)
);
CREATE INDEX ix_stock_batches_lookup ON stock_batches (hub_id, product_id, use_by);

-- Every change to a batch is recorded here. Forecasts read this table.
CREATE TABLE stock_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT NOT NULL,
  type VARCHAR(12) NOT NULL,
  quantity INT NOT NULL,
  reference VARCHAR(40),
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT fk_stock_movements_batch FOREIGN KEY (batch_id) REFERENCES stock_batches (id)
);
CREATE INDEX ix_stock_movements_batch ON stock_movements (batch_id);

CREATE TABLE customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone VARCHAR(15) NOT NULL,
  name VARCHAR(100),
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT uq_customers_phone UNIQUE (phone)
);

CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number VARCHAR(20) NOT NULL,
  hub_id BIGINT NOT NULL,
  customer_id BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL,
  delivery_address VARCHAR(300) NOT NULL,
  item_total_paise INT NOT NULL,
  delivery_fee_paise INT NOT NULL,
  total_paise INT NOT NULL,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT uq_orders_number UNIQUE (order_number),
  CONSTRAINT fk_orders_hub FOREIGN KEY (hub_id) REFERENCES hubs (id),
  CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);
CREATE INDEX ix_orders_hub_created ON orders (hub_id, created_at);

CREATE TABLE order_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  product_name VARCHAR(120) NOT NULL,
  unit_label VARCHAR(30) NOT NULL,
  unit_price_paise INT NOT NULL,
  quantity INT NOT NULL,
  line_total_paise INT NOT NULL,
  CONSTRAINT fk_order_lines_order FOREIGN KEY (order_id) REFERENCES orders (id),
  CONSTRAINT fk_order_lines_product FOREIGN KEY (product_id) REFERENCES products (id)
);
