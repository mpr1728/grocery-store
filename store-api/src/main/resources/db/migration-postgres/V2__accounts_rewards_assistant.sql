-- A customer becomes an account once a password is set. Guests who only ordered have none.
ALTER TABLE customers ADD COLUMN password_hash VARCHAR(100);
ALTER TABLE customers ADD COLUMN points_balance INT NOT NULL DEFAULT 0;

CREATE TABLE customer_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL,
  token_hash VARCHAR(64) NOT NULL,
  expires_at TIMESTAMP NOT NULL,
  CONSTRAINT uq_customer_sessions_token UNIQUE (token_hash),
  CONSTRAINT fk_customer_sessions_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);

-- Every change to a points balance is recorded here. The balance on the customer is the running total.
CREATE TABLE point_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL,
  points INT NOT NULL,
  reason VARCHAR(20) NOT NULL,
  order_number VARCHAR(20),
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT fk_point_entries_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);
CREATE INDEX ix_point_entries_customer ON point_entries (customer_id, id);

ALTER TABLE orders ADD COLUMN points_redeemed INT NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN points_discount_paise INT NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN points_earned INT NOT NULL DEFAULT 0;

-- One row per assistant message, used for the daily limit per customer.
CREATE TABLE assistant_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT fk_assistant_requests_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);
CREATE INDEX ix_assistant_requests_customer ON assistant_requests (customer_id, created_at);
