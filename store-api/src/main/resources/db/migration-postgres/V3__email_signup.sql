ALTER TABLE customers ADD CONSTRAINT uq_customers_email UNIQUE (email);

-- A sign-up waiting for the code sent by email. The account is created only once the code is confirmed.
CREATE TABLE signup_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash VARCHAR(64) NOT NULL,
  name VARCHAR(100) NOT NULL,
  phone VARCHAR(15) NOT NULL,
  email VARCHAR(254) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  code_hash VARCHAR(64) NOT NULL,
  attempts INT NOT NULL DEFAULT 0,
  expires_at TIMESTAMP NOT NULL,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT uq_signup_requests_token UNIQUE (token_hash)
);
CREATE INDEX ix_signup_requests_email ON signup_requests (email, created_at);
