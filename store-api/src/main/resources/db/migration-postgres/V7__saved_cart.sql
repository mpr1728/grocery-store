-- A signed-in customer's cart, kept so it is there on their next visit and on their other devices.
CREATE TABLE cart_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  quantity INT NOT NULL,
  CONSTRAINT uq_cart_lines UNIQUE (customer_id, product_id),
  CONSTRAINT fk_cart_lines_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
  CONSTRAINT fk_cart_lines_product FOREIGN KEY (product_id) REFERENCES products (id)
);
